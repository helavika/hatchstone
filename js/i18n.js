/** A line of text in the player's language; {0}, {1}… are filled in from the arguments. */
function tr(s, ...a) {
  const r = (LANG === "uk" && typeof UK[s] === "string" && UK[s]) || s;
  return a.length ? r.replace(/\{(\d)\}/g, (_, i) => a[i]) : r;
}
/** A counted word: English has one and many, Ukrainian one, few and many (1 осколок, 3 осколки, 5 осколків). */
function pl(n, one, many) {
  const f = LANG === "uk" && UK[one + "|" + many];
  if (!f) return n === 1 ? one : many;
  const a = Math.abs(n) % 100, b = a % 10;
  return f[b === 1 && a !== 11 ? 0 : b >= 2 && b <= 4 && (a < 10 || a >= 20) ? 1 : 2];
}
